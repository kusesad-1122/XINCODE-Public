package com.xincode.app

import com.xincode.data.AppDatabase
import com.xincode.data.SkillEntity

/**
 * 预制团队的专属技能。
 *
 * ## 技能和身份卡的分工
 *
 * 身份卡定义**这个人是谁**(他盯什么、不管什么、什么时候闭嘴)——它一直在上下文里。
 * 技能定义**某件事怎么做**(纪要什么格式、工时怎么拆、用例怎么列)——只在真要做那件事
 * 时才读进来。
 *
 * 这条线不划清楚就会两头出问题:把格式规范全塞进身份卡,每轮对话都在烧那几百 token,
 * 而且大部分轮次根本用不上;反过来把角色性格写进技能,模型不调用技能时就完全不进入状态。
 *
 * ## 为什么这些技能值得单独存在
 *
 * 它们解决的都是同一类问题:**模型知道该做什么,但产出的结构每次都不一样**。
 * 让工程师估工期,他有时给一个数、有时给一段散文、有时忘了说不确定性在哪。
 * 把「必须给区间、必须说清楚区间为什么这么宽」写成技能,产出才是可比、可用的。
 */
object TeamSkills {

    data class Skill(val name: String, val desc: String, val body: String)

    val SKILLS: List<Skill> = listOf(
        Skill(
            "会议纪要",
            "把一段多人讨论整理成可执行的纪要",
            """
            # 会议纪要

            把讨论整理成**能拿去干活**的纪要,不是聊天记录的摘要。

            ## 格式(严格按这个,不要写成散文)

            ```
            【已定】
            - <结论>(谁定的)

            【待定】
            - <问题>|等谁|卡在哪

            【行动项】
            - <做什么>|谁|什么时候

            【分歧】
            - <议题>:A 主张…,B 主张…,未收敛
            ```

