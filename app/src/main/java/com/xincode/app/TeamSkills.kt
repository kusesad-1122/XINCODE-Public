            "写PRD",
            "写需求文档:场景、验收标准、明确不做什么",
            """
            # 写 PRD

            ## 必须有的四段

            1. **要解决谁的什么问题** —— 一句话。写不出这一句说明需求还没想清楚,
               先别往下写。
            2. **用户场景** —— 具体到「谁、在什么情况下、想干什么、现在怎么做的」。
               不要写"用户希望更高效",那不是场景。
            3. **验收标准** —— 逐条可执行:做什么操作、期望看到什么。
               「体验流畅」不是验收标准,「列表滚动时不掉帧」也不是(谁来测?怎么测?),
               「1000 条数据下滚动到底部不出现空白占位」才是。
            4. **这一版不做什么** —— 明确列出来。这段比前三段更重要:
               不写清楚边界,开发过程中范围一定会漂。

            ## 规则

            - 需求超过三条时,标出优先级,并明确哪条可以砍。全都是 P0 等于没有优先级。
            - 每条需求配一个「不做会怎样」。答不上来的需求就是可以砍的。
            - 不要写技术方案。你可以给约束(要多快、要不要离线、包体上限),
              但不要指定用什么框架 —— 那是架构师的事,你越界只会让方案变差。

            ## 落盘

            写到工作区的 `PRD/<功能名>.md`。改动已有 PRD 时在文件末尾加「修订记录」,
            注明改了什么、为什么改 —— 光看最新版看不出决策是怎么变的。
            """.trimIndent()
        ),

