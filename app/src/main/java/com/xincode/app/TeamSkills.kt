    /** 角色 → 它该用的技能。装团队时一并写进身份卡的可用技能里。 */
    val BY_ROLE: Map<String, List<String>> = mapOf(
        "秘书助理" to listOf("会议纪要"),
        "产品经理" to listOf("写PRD"),
        "架构师" to listOf("技术方案"),
        "工程师" to listOf("工时评估"),
        "前端设计师" to listOf("交互方案"),
        "测试工程师" to listOf("测试用例")
    )

    /** 装进数据库。按名字查重,重复装不会攒出一堆同名技能。 */
    suspend fun install(database: AppDatabase) {
        val dao = database.skillDao()
        for (s in SKILLS) {
            if (dao.getByName(s.name) != null) continue
            dao.upsert(
                SkillEntity(
                    name = s.name,
                    description = s.desc,
                    content = s.body,
                    // 标成 bundled:这些是预制内容,后台复盘分身不该去改它们
                    source = "bundled"
                )
            )
        }
    }
