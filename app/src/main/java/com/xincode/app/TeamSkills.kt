            画出来的一定是"功能都在但不好用"。

            ## 四种状态一个都不能少

            大多数设计只画了理想状态,然后开发时才发现另外三种没人定义:

            1. **正常** —— 有数据、一切顺利
            2. **加载中** —— 等多久?骨架屏还是转圈?超过 3 秒怎么办?
            3. **空数据** —— 第一次用 vs 筛选后没结果,这两种文案不一样
            4. **出错** —— 错在哪、用户能做什么、有没有重试

            每种状态都要写清楚屏幕上到底显示什么。

            ## 描述要具体到能照着做

            不要写"简洁清晰"、"突出重点"。要写:

