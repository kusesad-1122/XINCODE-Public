    /** 装进数据库。按名字查重,重复装不会攒出一堆同名技能。 */
    suspend fun install(database: AppDatabase) {
        val dao = database.skillDao()
        for (s in SKILLS) {
            if (dao.getByName(s.name) != null) continue
            dao.upsert(
                SkillEntity(
                    name = s.name,
                    description = s.desc,
                    content = s.body,
                    source = "bundled"
                )
            )
        }
    }

    /** 所有技能名,给身份卡的工具白名单/技能选择器用。 */
    val NAMES: List<String> get() = SKILLS.map { it.name }
}
