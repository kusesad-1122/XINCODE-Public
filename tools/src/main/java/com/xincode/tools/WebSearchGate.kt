package com.xincode.tools

/**
 * 联网搜索/抓取总开关。【默认关闭】——不打开就完全不能联网获取信息
 * (web_search / web_fetch 不暴露给模型,主 agent 与子智能体都受控)。输入框「联网搜索」可切换。
 */
object WebSearchGate {
    @Volatile
    var enabled: Boolean = false

    /**
     * 关着的时候回给模型的话。
     *
     * 【为什么要写这么长】藏 schema 只能让模型「看不到」这个工具,不能阻止它凭印象去调。
     * 实测联网搜索关着时,模型会一路猜:先 `search_web`,再 `invoke_skill("联网搜索")`
     * ——把界面上的开关当成技能——每次都只拿到一句「未知工具」,于是继续猜到被防空转刹车掐掉,
     * 用户看到的就是一屏 `exit -1`。这里必须【指名道姓地堵掉这几条歧路】,并且给出唯一的出路
     * (让用户去开开关),模型才会停下来说人话,而不是接着试。
     */
    const val OFF_REASON: String =
        "被关掉了:「联网搜索」总开关默认关闭,现在是关闭状态,所有联网获取信息的路都不通。" +
            "别再换名字重试 —— search_web 不是别的工具,invoke_skill(\"联网搜索\") 也不是别的入口," +
            "它们都到不了这里。请直接告诉用户在输入框「+」里打开「联网搜索」,或者改用不联网的办法。"
}
