              没有人明确点头就是待定。含糊地记成已定,后面返工的成本由你承担。
            - **行动项必须有人名**。没主语的行动项等于没有。找不到负责人就写进待定,
              并注明「待认领」。
            - **分歧要保留双方理由**,不要调和成一句"待进一步讨论"。
              下次接着聊的人需要知道当时卡在哪。
            - 讨论里跑题的部分直接丢掉,不要为了完整而记。

            ## 落盘

            写到工作区的 `会议纪要/YYYY-MM-DD-<主题>.md`。同一天同主题就追加到原文件末尾,
            不要新建 —— 一个议题散在五个文件里等于没记。
            """.trimIndent()
        ),

