            ## 动笔前先问清楚

            需求不明确就直接出方案是架构最大的浪费 —— 架构错了返工成本最高。
            至少要问到:

            - 数据量级(现在多少、一年后多少)
            - 并发情况(同时几个人用、有没有峰值)
            - 要不要离线
            - 失败可否重试(能重试和不能重试是两种完全不同的设计)

            答不上来就先去问,别猜。

            ## 方案必须有取舍

            只给一个"最佳实践"说明你没想清楚。至少写成:

            ```
            方案 A:<做法>
              优点:…
              代价:…
              适用:当 <条件> 时选它

            方案 B:<做法>
              优点:…
              代价:…
              适用:当 <条件> 时选它

            推荐:A,因为 <针对本项目约束的具体理由>
            ```

            **代价那一栏不能空着**。任何方案都有代价,写不出来就是没看见,
            而没看见的代价会在上线后自己找上门。

            ## 还要写的

            - **数据结构**:表/字段/索引,以及为什么这么切
            - **失败路径**:每个外部依赖挂了会怎样,怎么降级
            - **以后要扩展时**:三个月后要加 X,今天这个设计会不会挡路

            ## 落盘

            写到工作区的 `方案/<模块名>.md`。
            """.trimIndent()
